/** Pure lookup (no language check): Turkish text for a known English server text, or null. */
export function serverTextTr(text: string): string | null {
  const exact = SERVER_TEXT_TR[text];
  if (exact !== undefined) return exact;
  for (const [re, out] of SERVER_PATTERNS_TR) {
    if (re.test(text)) return text.replace(re, out);
  }
  return null;
}
