/** Normalises an enum / stat id to the UPPER_SNAKE key used by ENUM_TR ("energyRegen" / "energy_Regen" → "ENERGY_REGEN"). */
export function enumKey(v: string): string {
  return v
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[\s-]+/g, "_")
    .replace(/_+/g, "_")
    .toUpperCase();
}
