/** Pattern-based item descriptions ("Name (TYPE).", blueprint unlock texts). */
function itemPatternTr(desc: string): string | null {
  const typed = /^(.+) \(([A-Z_]+)\)\.$/.exec(desc);
  if (typed?.[1] && typed[2]) {
    const label = ENUM_TR[enumKey(typed[2])];
    if (label) return `${typed[1]} (${label}).`;
  }
  const bp = /^Unlocks the (.+) recipe \((\w+) tier\)\.$/.exec(desc);
  if (bp?.[1] && bp[2]) return `${bp[1]} tarifini açar (${TIER_TR[bp[2]] ?? bp[2]} kademe).`;
  return null;
}

/** Turkish description for an inventory item / item definition id (null = keep the English original). */
export function itemDescTr(itemId: string, english: string): string | null {
  const direct = ITEM_DESC_TR[itemId];
  if (direct) return direct;
  const base = itemId.replace(/^item_/, "");
  const shared = SHIP_DESC_TR[base] ?? SHIP_DESC_TR[`ship_${base.replace(/^ship_/, "")}`] ?? MODULE_DESC_TR[base];
  if (shared) return shared;
  return itemPatternTr(english);
}
